#!/usr/bin/env python3
"""Self-hosted Fraunces, pinned to the one softness the site uses (performance budget, brief 11).

Every Fraunces rule on the page sets 'SOFT' 100 (type.css), so the SOFT axis is pinned at 100 and
dropped: the files come out about half the size with identical glyphs. wght, opsz and WONK stay
variable. Each style is split into Google's three subsets (latin, latin-ext, vietnamese) behind
unicode-range, like next/font did, so only latin is preloaded and the rest load on demand.

    python3 -m venv /tmp/fontvenv && /tmp/fontvenv/bin/pip install fonttools brotli
    /tmp/fontvenv/bin/python scripts/fonts.py path/to/Fraunces[SOFT,WONK,opsz,wght].ttf \
        path/to/Fraunces-Italic[SOFT,WONK,opsz,wght].ttf

Sources: github.com/google/fonts/tree/main/ofl/fraunces (OFL). Writes public/fonts/*.woff2 (content-
hashed names, cached immutably via vercel.json), src/styles/fonts.css (the @font-face rules, the
metric-matched fallback and --font-display) and src/app/fontPreload.ts (the latin URLs to preload).
"""

import hashlib
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public" / "fonts"

# Google Fonts' subset ranges for Fraunces (as served to next/font).
SUBSETS = {
    "latin": "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,"
    "U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
    "latin-ext": "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,"
    "U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C4,U+2113,U+2C60-2C7F,U+A720-A7FF",
    "vietnamese": "U+0102-0103,U+0110-0111,U+0128-0129,U+0168-0169,U+01A0-01A1,U+01AF-01B0,U+0300-0301,"
    "U+0303-0304,U+0308-0309,U+0323,U+0329,U+1EA0-1EF9,U+20AB",
}

# next/font's metric-matched fallback for Fraunces (no layout shift when the font swaps in).
FALLBACK = "src: local('Times New Roman'); ascent-override: 84.71%; descent-override: 22.09%; line-gap-override: 0%; size-adjust: 115.45%;"


def codepoints(ranges: str) -> list[int]:
    out: list[int] = []
    for part in ranges.split(","):
        part = part.strip().removeprefix("U+")
        lo, _, hi = part.partition("-")
        out.extend(range(int(lo, 16), int(hi or lo, 16) + 1))
    return out


def build(src: Path, style: str) -> dict[str, str]:
    pinned = instancer.instantiateVariableFont(TTFont(src), {"SOFT": 100})
    buf = io.BytesIO()
    pinned.save(buf)
    files: dict[str, str] = {}
    for name, ranges in SUBSETS.items():
        font = TTFont(io.BytesIO(buf.getvalue()))
        opts = subset.Options()
        opts.layout_features = ["*"]
        opts.flavor = "woff2"
        opts.hinting = False
        opts.name_IDs = ["*"]
        opts.notdef_outline = True
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=codepoints(ranges))
        sub.subset(font)
        out = io.BytesIO()
        font.flavor = "woff2"
        font.save(out)
        data = out.getvalue()
        digest = hashlib.sha256(data).hexdigest()[:10]
        fname = f"fraunces-{style}-{name}.{digest}.woff2"
        (OUT / fname).write_bytes(data)
        files[name] = fname
        print(f"[fonts] {fname} {len(data) // 1024}KB")
    return files


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("usage: fonts.py <Fraunces roman variable ttf> <Fraunces italic variable ttf>")
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("fraunces-*.woff2"):
        old.unlink()
    built = {"normal": build(Path(sys.argv[1]), "roman"), "italic": build(Path(sys.argv[2]), "italic")}

    faces = []
    for style, files in built.items():
        for name, fname in files.items():
            faces.append(
                "@font-face {\n"
                "  font-family: 'Fraunces';\n"
                f"  font-style: {style};\n"
                "  font-weight: 100 900;\n"
                "  font-display: swap;\n"
                f"  src: url('/fonts/{fname}') format('woff2');\n"
                f"  unicode-range: {SUBSETS[name]};\n"
                "}"
            )
    css = (
        "/* GENERATED by scripts/fonts.py: self-hosted Fraunces with SOFT pinned at 100. Do not edit by hand. */\n"
        + "\n".join(faces)
        + "\n@font-face {\n  font-family: 'Fraunces Fallback';\n  "
        + FALLBACK
        + "\n}\n:root {\n  --font-display: 'Fraunces', 'Fraunces Fallback';\n}\n"
    )
    (ROOT / "src" / "styles" / "fonts.css").write_text(css)
    preload = (
        "// GENERATED by scripts/fonts.py. The latin Fraunces files, preloaded in <head> (src/app/layout.tsx).\n"
        "export const FONT_PRELOADS = [\n"
        + "".join(f"  '/fonts/{built[s]['latin']}',\n" for s in ("normal", "italic"))
        + "] as const;\n"
    )
    (ROOT / "src" / "app" / "fontPreload.ts").write_text(preload)


if __name__ == "__main__":
    main()
