// Writes src/components/ui/brandSvgs.ts from the brand kit's SVGs in assets/brand/ (copied byte-identical
// from docs/brand/svg/ on the brand branch). Metro can't import an .svg as text, so the app renders these
// strings with react-native-svg's SvgXml. Run it after the kit changes; scripts/test-brand.mjs checks the
// strings still match the files byte for byte.
//   node scripts/sync-brand.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets/brand');

export function brandFiles() {
  const top = readdirSync(dir).filter((f) => f.endsWith('.svg'));
  const moods = readdirSync(join(dir, 'mascot')).filter((f) => f.endsWith('.svg')).map((f) => `mascot/${f}`);
  return [...top, ...moods].sort();
}

export function readBrand(file) {
  return readFileSync(join(dir, file), 'utf8');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const lines = brandFiles().map((f) => `  '${f}': ${JSON.stringify(readBrand(f))},`);
  const out = [
    '// GENERATED by scripts/sync-brand.mjs from assets/brand/ (the brand kit, byte-identical). Do not edit:',
    '// change the kit, copy its files into assets/brand/, then run `node scripts/sync-brand.mjs`.',
    'export const BRAND_SVGS = {',
    ...lines,
    '} as const;',
    '',
    'export type BrandFile = keyof typeof BRAND_SVGS;',
    '',
  ].join('\n');
  writeFileSync(join(root, 'src/components/ui/brandSvgs.ts'), out);
  console.log(`wrote src/components/ui/brandSvgs.ts (${lines.length} files)`);
}
